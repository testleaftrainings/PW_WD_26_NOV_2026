// Explain what a function is.
// A function is a reusable block of code designed to perform a specific task.

// Declare a function using the function keyword followed by the function name.
function functionName() {

    // Print a message when the function is executed.
    console.log("This is from a function");
}

// Call the function to execute its code.
functionName();

// Declare a function named addNumbers to perform addition.
function addNumbers() {

    // Declare a variable a and assign the value 10.
    let a = 10;

    // Declare a variable b and assign the value 30.
    let b = 30;

    // Add a and b, and print the result.
    console.log(a + b);
}

// Call the addNumbers function to execute the addition.
addNumbers();

// Expected Output:
// This is from a function
// 40