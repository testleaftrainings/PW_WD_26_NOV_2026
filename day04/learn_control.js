// Declare a function named functionName.
function learnForLoop() {

    // Start a for loop with i initialized to 0, continue while i is less than 5, and increment i by 1 after each iteration.
    for (let i = 0; i < 5; i++) {

        // Print the current value of i to the console.
        console.log(i);
    }
}

// Call the functionName function to execute the loop.
learnForLoop();

// Expected Output:
// 0
// 1
// 2
// 3
// 4
