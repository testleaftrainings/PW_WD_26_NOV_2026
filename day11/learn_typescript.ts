// Declare a variable named age with the number type and assign the value 100.
let age: number = 100;

// Attempt to assign a string value to the age variable.
// This causes a TypeScript compilation error because age is declared as a number.
age = "Vineeth";

// JavaScript is dynamically typed, so the type of a variable can change at runtime.
// JavaScript - Dynamically Typed

// TypeScript is statically typed, so the type of a variable is checked during compilation.
// TypeScript - Statically Typed

// TypeScript supports type inference, where the type is automatically determined from the assigned value.
// TypeScript - Implicit Inference

// TypeScript also supports explicit type annotations, where the developer specifies the type.
// TypeScript - Explicit Inference