// ==========================================
// CHECK WHETHER A NUMBER IS POSITIVE, NEGATIVE, OR ZERO
// ==========================================

// Declare a variable and assign the value 5.
var inputNumber = 5;

// Check whether the number is less than zero.
if (inputNumber < 0) {
    // If the condition is true, print that the number is negative.
    console.log("The number is a negative number");
}

// Check whether the number is greater than zero.
else if (inputNumber > 0) {
    // If the condition is true, print that the number is positive.
    console.log("The number is a positive number");
}

// If both conditions are false, the number must be zero.
else {
    // Print that the number is zero.
    console.log("The number is zero");
}


